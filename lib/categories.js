const norm = (s) => (s || '').toString().toLowerCase().replace(/ё/g, 'е');

function detectCategory(text) {
  const t = norm(text);
  let best = null;
  for (const cat of CATEGORIES) {
    for (const kw of cat.keywords) {
      const k = norm(kw);
      if (k && t.includes(k) && (!best || k.length > best.kw.length)) best = { cat, kw: k };
    }
  }
  return best ? best.cat : CATEGORIES[CATEGORIES.length - 1];
}

// Для /budget: находим категорию по началу названия («кафе», «продукты»).
function findCategoryByName(query) {
  const q = norm(query);
  if (!q) return null;
  return (
    CATEGORIES.find((c) => norm(c.name).startsWith(q)) ||
    CATEGORIES.find((c) => norm(c.name).includes(q)) ||
    null
  );
}

function catEmoji(name) {
  const cat = CATEGORIES.find((c) => c.name === name);
  return (cat && cat.emoji) || '📦';
}

